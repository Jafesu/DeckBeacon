#!/usr/bin/env python3
"""Generate the Marketplace/Decky mirror repositories from the monorepo (ADR-0005).

The mirrors are release-only and never edited by hand: everything in them comes
from this script. Usage:

    python3 scripts/build_mirrors.py --ha DIR --card DIR [--decky DIR]

Each DIR is a checkout of the mirror repository; its tracked content (except
.git) is replaced. The card bundle must be built first (apps/dashboard: npm run build).
"""

from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MONOREPO = "https://github.com/Jafesu/DeckBeacon"
HA_MIN = "2026.5.0"


def commit() -> str:
    return subprocess.run(
        ["git", "-C", str(ROOT), "rev-parse", "--short", "HEAD"],
        check=True,
        capture_output=True,
        text=True,
    ).stdout.strip()


def clean(dest: Path) -> None:
    if not (dest / ".git").exists():
        sys.exit(f"{dest} is not a git checkout")
    for p in dest.iterdir():
        if p.name == ".git":
            continue
        shutil.rmtree(p) if p.is_dir() else p.unlink()


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)


def release_workflow(version_cmd: str, assets: str) -> str:
    """Publish v<version> when a push to main carries a version without a release.

    GitHub creates the tag from the release (no tag pushes needed)."""
    return f"""# Generated by scripts/build_mirrors.py in {MONOREPO}. Do not edit here.
name: Release
on:
  push:
    branches: [main]
  workflow_dispatch:
permissions:
  contents: write
jobs:
  release:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v5
      - name: Publish a release for a new version
        env:
          GH_TOKEN: ${{{{ github.token }}}}
        run: |
          version="$({version_cmd})"
          tag="v$version"
          if gh release view "$tag" >/dev/null 2>&1; then echo "$tag already released"; exit 0; fi
          gh release create "$tag" --target "$GITHUB_SHA" --title "$tag" --notes "Generated from {MONOREPO} (see SOURCE). Changelog and issues live in the monorepo." {assets}
"""


def build_ha(dest: Path, src_commit: str) -> str:
    clean(dest)
    src = ROOT / "apps/homeassistant/custom_components/deckbeacon"
    shutil.copytree(
        src,
        dest / "custom_components/deckbeacon",
        ignore=shutil.ignore_patterns("__pycache__", "*.pyc"),
    )
    version = json.loads((src / "manifest.json").read_text())["version"]
    write(
        dest / "hacs.json",
        json.dumps(
            {"name": "DeckBeacon", "homeassistant": HA_MIN, "render_readme": True},
            indent=2,
        )
        + "\n",
    )
    (dest / "images").mkdir(exist_ok=True)
    shutil.copy(ROOT / "docs/brand/png/readme-banner.png", dest / "images/banner.png")
    write(
        dest / "README.md",
        f"""<p align="center"><img src="images/banner.png" alt="DeckBeacon" width="600"></p>

# DeckBeacon for Home Assistant

Home Assistant integration for **DeckBeacon**: local-first monitoring and management of SteamOS devices (Steam Deck and other SteamOS PCs). It shows system telemetry, power state, the Steam library and current game, live downloads and game artwork, and launches games, using native Home Assistant entities and actions.

> **Pre-release.** This repository is generated from the [DeckBeacon monorepo]({MONOREPO}); please file issues and read the docs there.

## Requirements
- Home Assistant {HA_MIN} or newer.
- The DeckBeacon agent running on the SteamOS device (see the monorepo).
- Optional: the [DeckBeacon cards](https://github.com/Jafesu/deckbeacon-card) for the dashboard.

## Install
Marketplace → **Add from link** → `https://github.com/Jafesu/deckbeacon-homeassistant` (type: Integration). Restart Home Assistant, then pair the device from the agent with `deckbeacon pair`.

Version {version}, built from monorepo commit `{src_commit}`.
""",
    )
    write(dest / "SOURCE", f"{MONOREPO}/commit/{src_commit}\n")
    write(
        dest / ".github/workflows/release.yml",
        release_workflow(
            "python3 -c \"import json;print(json.load(open('custom_components/deckbeacon/manifest.json'))['version'])\"",
            "",
        ),
    )
    return version


def build_card(dest: Path, src_commit: str) -> str:
    clean(dest)
    dash = ROOT / "apps/dashboard"
    bundle = dash / "dist/deckbeacon-cards.js"
    if not bundle.exists():
        sys.exit("build the cards first: (cd apps/dashboard && npm run build)")
    version = json.loads((dash / "package.json").read_text())["version"]
    shutil.copy(bundle, dest / "deckbeacon-cards.js")
    write(
        dest / "hacs.json",
        json.dumps(
            {
                "name": "DeckBeacon Cards",
                "filename": "deckbeacon-cards.js",
                "homeassistant": HA_MIN,
                "render_readme": True,
            },
            indent=2,
        )
        + "\n",
    )
    (dest / "images").mkdir(exist_ok=True)
    shutil.copy(ROOT / "docs/brand/png/readme-banner.png", dest / "images/banner.png")
    shutil.copy(
        ROOT / "docs/milestones/M8-evidence/cards-dark-1280.png",
        dest / "images/cards-dark.png",
    )
    write(
        dest / "package.json",
        json.dumps(
            {"name": "deckbeacon-cards", "version": version, "private": True}, indent=2
        )
        + "\n",
    )
    write(
        dest / "README.md",
        f"""<p align="center"><img src="images/banner.png" alt="DeckBeacon" width="600"></p>

# DeckBeacon cards

Optional Lovelace cards for the [DeckBeacon integration](https://github.com/Jafesu/deckbeacon-homeassistant). The integration works fully without them.

<img src="images/cards-dark.png" alt="DeckBeacon cards in a dark theme" width="800">

| Card | Shows |
|---|---|
| `custom:deckbeacon-now-playing-card` | Current game with Steam artwork, session time, Rich Presence activity |
| `custom:deckbeacon-device-card` | Connection, power, Gaming/Desktop session, temperatures, storage |
| `custom:deckbeacon-downloads-card` | Download progress, speed, time remaining |
| `custom:deckbeacon-library-card` | Game library with artwork, search, filters, launch with confirmation |
| `custom:deckbeacon-performance-card` | CPU/GPU/memory with live trends, temperatures, fan |

Every card has a visual editor; `device_id` is optional (defaults to the first DeckBeacon device).

```yaml
type: custom:deckbeacon-library-card
device_id: <your device>   # optional
sort: recent               # optional: name | recent
```

A ready-made dashboard with one view per device:

```yaml
strategy:
  type: custom:deckbeacon
```

## Install
Marketplace → **Add from link** → `https://github.com/Jafesu/deckbeacon-card` (type: Dashboard). The resource is registered automatically.

> **Pre-release.** Generated from the [DeckBeacon monorepo]({MONOREPO}); issues and docs live there. Version {version}, monorepo commit `{src_commit}`.
""",
    )
    write(dest / "SOURCE", f"{MONOREPO}/commit/{src_commit}\n")
    write(
        dest / ".github/workflows/release.yml",
        release_workflow(
            "python3 -c \"import json;print(json.load(open('package.json'))['version'])\"",
            "deckbeacon-cards.js",
        ),
    )
    return version


def build_decky(dest: Path, src_commit: str) -> None:
    clean(dest)
    write(
        dest / "README.md",
        f"""# DeckBeacon for Decky Loader

The optional Decky Loader plugin for DeckBeacon (pairing, agent status and notifications inside Gaming Mode).

**Not released yet.** The plugin is planned for milestone M4. This repository will hold the generated plugin (at the root, for the Decky plugin store), built from the [DeckBeacon monorepo]({MONOREPO}).

Monorepo commit `{src_commit}`.
""",
    )


def main() -> None:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("--ha", type=Path)
    ap.add_argument("--card", type=Path)
    ap.add_argument("--decky", type=Path)
    a = ap.parse_args()
    c = commit()
    if a.ha:
        print("deckbeacon-homeassistant", build_ha(a.ha, c))
    if a.card:
        print("deckbeacon-card", build_card(a.card, c))
    if a.decky:
        build_decky(a.decky, c)
        print("deckbeacon-decky placeholder")


if __name__ == "__main__":
    main()
